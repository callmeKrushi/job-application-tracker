def row_to_application(row):
    """Convert a query result tuple into the dictionary used by the app layer."""
    return {
        "id": row[0],
        "company": row[1],
        "role": row[2],
        "location": row[3],
        "job_type": row[4],
        "salary": row[5],
        "job_url": row[6],
        "notes": row[7],
        "status": row[8],
        "date_applied": row[9],
    }


def show_table_structure():
    """Return column metadata in a PRAGMA-like tuple shape for existing callers."""
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    c.ordinal_position - 1 AS cid,
                    c.column_name,
                    c.data_type,
                    NULL AS unused_1,
                    (c.is_nullable = 'NO') AS not_null,
                    c.column_default,
                    CASE WHEN EXISTS (
                        SELECT 1
                        FROM information_schema.table_constraints AS tc
                        JOIN information_schema.key_column_usage AS kcu
                          ON tc.constraint_name = kcu.constraint_name
                         AND tc.table_schema = kcu.table_schema
                         AND tc.table_name = kcu.table_name
                        WHERE tc.table_schema = c.table_schema
                          AND tc.table_name = c.table_name
                          AND tc.constraint_type = 'PRIMARY KEY'
                          AND kcu.column_name = c.column_name
                    ) THEN 1 ELSE 0 END AS pk
                FROM information_schema.columns AS c
                WHERE c.table_schema = 'public' AND c.table_name = 'applications'
                ORDER BY c.ordinal_position
                """
            )
            columns = cursor.fetchall()
    return columns


def migrate_database():
    """Add columns used by the current app to an older PostgreSQL applications table.

    This upgrades a legacy table already inside PostgreSQL. It does not import the
    separate SQLite applications.db file; that data transfer is a separate step.
    """
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                ALTER TABLE applications
                    ADD COLUMN IF NOT EXISTS location TEXT,
                    ADD COLUMN IF NOT EXISTS job_type TEXT,
                    ADD COLUMN IF NOT EXISTS salary TEXT,
                    ADD COLUMN IF NOT EXISTS job_url TEXT,
                    ADD COLUMN IF NOT EXISTS notes TEXT,
                    ADD COLUMN IF NOT EXISTS date_applied TEXT
                """
            )
            cursor.execute(
                """
                UPDATE applications
                SET date_applied = CURRENT_DATE::TEXT
                WHERE date_applied IS NULL
                """
            )
            cursor.execute(
                "ALTER TABLE applications ALTER COLUMN date_applied SET NOT NULL"
            )
            cursor.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_applications_status
                ON applications(status)
                """
            )
    print("PostgreSQL database migration completed successfully!")
