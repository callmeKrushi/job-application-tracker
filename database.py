"""PostgreSQL persistence layer for the Job Application Tracker."""

import os
from contextlib import contextmanager

import psycopg
from dotenv import load_dotenv

# Load local development settings from the project-level .env file.
load_dotenv()


def get_connection():
    """Create a connection to the configured PostgreSQL database."""
    required_settings = {
        "DB_HOST": os.getenv("DB_HOST"),
        "DB_PORT": os.getenv("DB_PORT"),
        "DB_NAME": os.getenv("DB_NAME"),
        "DB_USER": os.getenv("DB_USER"),
        "DB_PASSWORD": os.getenv("DB_PASSWORD"),
    }
    missing_settings = [name for name, value in required_settings.items() if not value]
    if missing_settings:
        raise RuntimeError(
            "Missing database configuration in .env: " + ", ".join(missing_settings)
        )

    return psycopg.connect(
        host=required_settings["DB_HOST"],
        port=int(required_settings["DB_PORT"]),
        dbname=required_settings["DB_NAME"],
        user=required_settings["DB_USER"],
        password=required_settings["DB_PASSWORD"],
    )


@contextmanager
def get_db():
    """Yield a connection, commit on success, roll back on failure, and close."""
    connection = get_connection()
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def create_table():
    """Create the applications table and its status index if they do not exist."""
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS applications (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company TEXT NOT NULL,
                    role TEXT NOT NULL,
                    location TEXT,
                    job_type TEXT,
                    salary TEXT,
                    job_url TEXT,
                    notes TEXT,
                    status TEXT NOT NULL,
                    date_applied TEXT NOT NULL,
                    follow_up_date DATE
                )
                """
            )
            cursor.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_applications_status
                ON applications(status)
                """
            )


def add_application(
    company,
    role,
    location,
    job_type,
    salary,
    job_url,
    notes,
    status,
    date_applied,
    follow_up_date=None,
):
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO applications (
                    company, role, location, job_type, salary,
                    job_url, notes, status, date_applied, follow_up_date
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    company, role, location, job_type, salary,
                    job_url, notes, status, date_applied, follow_up_date,
                ),
            )
            application_id = cursor.fetchone()[0]
    return application_id


def get_applications():
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT * FROM applications ORDER BY id")
            rows = cursor.fetchall()
    return [row_to_application(row) for row in rows]



def get_application_stats():
    """Return total applications and counts grouped by status."""
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COUNT(*) AS total,
                    COUNT(*) FILTER (WHERE status = 'Applied') AS applied,
                    COUNT(*) FILTER (WHERE status = 'Interview') AS interview,
                    COUNT(*) FILTER (WHERE status = 'Selected') AS selected,
                    COUNT(*) FILTER (WHERE status = 'Rejected') AS rejected,
                    COUNT(*) FILTER (WHERE status = 'Withdrawn') AS withdrawn
                FROM applications
                """
            )
            row = cursor.fetchone()

    return {
        "total": row[0],
        "applied": row[1],
        "interview": row[2],
        "selected": row[3],
        "rejected": row[4],
        "withdrawn": row[5],
    }



def get_response_rate():
    """Return the number and percentage of applications with a response."""
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COUNT(*) AS total,
                    COUNT(*) FILTER (
                        WHERE status IN ('Interview', 'Selected', 'Rejected')
                    ) AS responded
                FROM applications
                """
            )
            row = cursor.fetchone()

    total = row[0]
    responded = row[1]
    response_rate = (responded / total * 100) if total else 0.0

    return {
        "total": total,
        "responded": responded,
        "response_rate": round(response_rate, 2),
    }


def get_monthly_application_stats():
    """Return the number of applications submitted each month."""
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    TO_CHAR(
                        TO_DATE(date_applied, 'YYYY-MM-DD'),
                        'YYYY-MM'
                    ) AS month,
                    COUNT(*) AS total
                FROM applications
                GROUP BY month
                ORDER BY month
                """
            )
            rows = cursor.fetchall()

    return [
        {"month": row[0], "total": row[1]}
        for row in rows
    ]



def search_applications(search_term):
    pattern = f"%{search_term}%"
    with get_db() as connection:
        with connection.cursor() as cursor:
            # ILIKE preserves SQLite's usual case-insensitive text search behavior.
            cursor.execute(
                """
                SELECT * FROM applications
                WHERE company ILIKE %s OR role ILIKE %s
                ORDER BY id
                """,
                (pattern, pattern),
            )
            rows = cursor.fetchall()
    return [row_to_application(row) for row in rows]


def filter_applications(status):
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM applications WHERE status = %s ORDER BY id",
                (status,),
            )
            rows = cursor.fetchall()
    return [row_to_application(row) for row in rows]


def sort_applications(order):
    # Only choose between these fixed SQL fragments; never interpolate user input.
    sort_direction = "DESC" if order == "desc" else "ASC"
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                f"SELECT * FROM applications ORDER BY date_applied {sort_direction}"
            )
            rows = cursor.fetchall()
    return [row_to_application(row) for row in rows]


def update_application_status(application_id, new_status):
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                "UPDATE applications SET status = %s WHERE id = %s",
                (new_status, application_id),
            )
            rows_updated = cursor.rowcount
    return rows_updated


def delete_application(application_id):
    with get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                "DELETE FROM applications WHERE id = %s",
                (application_id,),
            )
            rows_deleted = cursor.rowcount
    return rows_deleted


