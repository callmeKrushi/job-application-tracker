def test_migrate_database(test_database):
    # Replace the current table with a legacy PostgreSQL schema.
    with test_database.get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute("DROP TABLE applications CASCADE")
            cursor.execute(
                """
                CREATE TABLE applications (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company TEXT NOT NULL,
                    role TEXT NOT NULL,
                    status TEXT NOT NULL
                )
                """
            )
            cursor.execute(
                """
                INSERT INTO applications (company, role, status)
                VALUES (%s, %s, %s)
                """,
                ("Google", "Python Developer", "Applied"),
            )

    test_database.migrate_database()

    with test_database.get_db() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'applications'
                ORDER BY ordinal_position
                """
            )
            column_names = [row[0] for row in cursor.fetchall()]
            cursor.execute("SELECT * FROM applications")
            applications = cursor.fetchall()

    assert column_names == [
        "id", "company", "role", "status", "location", "job_type",
        "salary", "job_url", "notes", "date_applied", "follow_up_date",
    ]
    assert len(applications) == 1
    assert applications[0][1] == "Google"
    assert applications[0][2] == "Python Developer"
    assert applications[0][3] == "Applied"
    assert applications[0][9] is not None


def test_get_db_rolls_back_on_error(test_database):
    try:
        with test_database.get_db() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO applications (company, role, status, date_applied)
                    VALUES (%s, %s, %s, %s)
                    """,
                    ("TestCompany", "TestRole", "Applied", "2026-10-11"),
                )
            raise ValueError("Simulated database failure")
    except ValueError as error:
        assert str(error) == "Simulated database failure"

    assert test_database.get_applications() == []


def test_get_db_closes_connection_on_error(test_database):
    connection = None
    try:
        with test_database.get_db() as db_connection:
            connection = db_connection
            raise ValueError("Simulated error")
    except ValueError as error:
        assert str(error) == "Simulated error"

    assert connection is not None
    with pytest.raises(psycopg.OperationalError, match="closed"):
        connection.execute("SELECT 1")


